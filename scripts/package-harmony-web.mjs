import { cp, lstat, mkdir, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(repoRoot, "apps/web/out");
const destination = path.join(repoRoot, "apps/harmony/entry/src/main/resources/rawfile/site");
const markerName = ".harmony-web-output";
const excludedNames = new Set([
  "audio",
  "data",
  "story-images",
  "textbook-pages",
  "SHA256SUMS",
  "RELEASE-INSTALL.md",
  "manifest.json",
  "sw.js",
]);

async function exists(filePath) {
  try {
    await stat(filePath);
    return true;
  } catch (error) {
    if (error.code === "ENOENT") return false;
    throw error;
  }
}

async function copyWebShell() {
  if (!(await exists(source))) {
    throw new Error(`静态导出目录不存在：${source}。请先运行 npm run build。`);
  }

  const indexPath = path.join(source, "index.html");
  const nextStaticPath = path.join(source, "_next/static");
  if (!(await exists(indexPath)) || !(await exists(nextStaticPath))) {
    throw new Error("Next.js 导出产物不完整：缺少 index.html 或 _next/static。");
  }

  if (await exists(destination)) {
    const markerPath = path.join(destination, markerName);
    if (!(await exists(markerPath))) {
      throw new Error(`拒绝覆盖非脚本生成的目录：${destination}`);
    }
    await rm(destination, { recursive: true, force: true });
  }

  await mkdir(destination, { recursive: true });
  const entries = await readdir(source, { withFileTypes: true });
  for (const entry of entries) {
    if (excludedNames.has(entry.name) || entry.name.endsWith(".zip") || entry.name.endsWith(".tar.gz")) {
      continue;
    }
    await cp(path.join(source, entry.name), path.join(destination, entry.name), {
      recursive: true,
      dereference: false,
      filter: async (sourcePath) => {
        const info = await lstat(sourcePath);
        return !info.isSymbolicLink();
      },
    });
  }

  await writeFile(path.join(destination, markerName), "generated by package-harmony-web.mjs\n");

  const copiedIndex = await readFile(path.join(destination, "index.html"), "utf8");
  if (!copiedIndex.includes("_next/static/")) {
    throw new Error("导出首页没有引用 _next/static，拒绝生成 Harmony 页面壳。");
  }

  const size = await directorySize(destination);
  console.log(`Harmony Web 页面壳已准备：${destination}`);
  console.log(`大小：${formatBytes(size)}（四类课程资源与压缩包未复制）`);
}

async function directorySize(directory) {
  let total = 0;
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isDirectory()) total += await directorySize(entryPath);
    else if (entry.isFile()) total += (await stat(entryPath)).size;
  }
  return total;
}

function formatBytes(bytes) {
  const units = ["B", "KB", "MB", "GB"];
  let value = bytes;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit += 1;
  }
  return `${value.toFixed(unit === 0 ? 0 : 1)} ${units[unit]}`;
}

copyWebShell().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
